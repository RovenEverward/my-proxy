#!/usr/bin/env node
// Import official SVGs once. Keep their bytes and geometry unchanged.
// Usage: node scripts/sync-ui-icons.mjs [path/to/lucide-static-VERSION.tgz]
// Check: node scripts/sync-ui-icons.mjs --check
// The check uses committed assets and provenance. It needs no network or archive.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG = resolve(ROOT, "internal/ui/icons.json");
const ASSETS = resolve(ROOT, "internal/ui/assets/icons/lucide");
const GENERATED = resolve(ROOT, "internal/ui/frontend/components/icon-map.ts");
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const json = value => JSON.stringify(value, null, 2) + "\n";

function configuration() {
  const bytes = readFileSync(CONFIG);
  const config = JSON.parse(bytes.toString("utf8"));
  const { source, icons } = config;
  if (config.schemaVersion !== 1 || source?.package !== "lucide-static" || !/^\d+\.\d+\.\d+$/.test(source.version)) {
    throw new Error("icons.json must pin one exact lucide-static version");
  }
  const officialTarball = `https://registry.npmjs.org/lucide-static/-/lucide-static-${source.version}.tgz`;
  if (source.tarballUrl !== officialTarball || !/^[a-f0-9]{64}$/.test(source.archiveSha256)) {
    throw new Error("icons.json must record the official npm tarball URL and SHA-256");
  }
  if (!icons || typeof icons !== "object" || Array.isArray(icons) || !Object.keys(icons).length) {
    throw new Error("icons.json must contain the legacy-to-official icon map");
  }
  const entries = Object.entries(icons).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  for (const [legacy, official] of entries) {
    if (!/^[a-z][a-z0-9]*$/.test(legacy) || typeof official !== "string" || !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(official)) {
      throw new Error(`Invalid icon mapping: ${legacy} -> ${official}`);
    }
  }
  const names = [...new Set(entries.map(([, name]) => name))].sort();
  return { source, entries, names, configSha256: sha256(bytes) };
}

// The caller supplies an absolute archive path. Entry names come only from the
// validated map. Read exact entries without extracting paths or invoking a shell.
function archiveEntry(archive, entry) {
  return execFileSync("tar", ["-xOf", archive, entry], { maxBuffer: 4 * 1024 * 1024 });
}

function importAssets(config, archive) {
  if (sha256(readFileSync(archive)) !== config.source.archiveSha256) {
    throw new Error("Archive SHA-256 does not match the pinned official package");
  }
  const pkg = JSON.parse(archiveEntry(archive, "package/package.json").toString("utf8"));
  if (pkg.name !== config.source.package || pkg.version !== config.source.version) {
    throw new Error("Archive package name or version does not match icons.json");
  }
  const assets = new Map([["LICENSE", archiveEntry(archive, "package/LICENSE")]]);
  for (const name of config.names) assets.set(name + ".svg", archiveEntry(archive, `package/icons/${name}.svg`));
  return assets;
}

function svgBody(bytes, name) {
  const svg = bytes.toString("utf8");
  const match = /^(?:<!--[^]*?-->\s*)?<svg\b([^>]*)>([^]*)<\/svg>\s*$/.exec(svg);
  if (!match || !/\bviewBox="0 0 24 24"/.test(match[1])) {
    throw new Error(`Expected the official 24×24 SVG: ${name}`);
  }
  // Keep the inner XML verbatim. The shared ic() owns the outer SVG attributes.
  return match[2];
}

function generatedScript(config, assets) {
  for (const name of config.names) svgBody(assets.get(name + ".svg"), name);
  const component = name => name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join("");
  const imports = config.names.map(component).join(", ");
  return `// Generated by scripts/sync-ui-icons.mjs. Edit internal/ui/icons.json instead.\n` +
    `// Official Lucide ${config.source.version}; SVG provenance: assets/icons/lucide/SOURCES.json.\n` +
    `import { ${imports} } from "lucide-react";\n\n` +
    `export const ICON_NAMES = Object.freeze(${JSON.stringify(Object.fromEntries(config.entries), null, 2)});\n\n` +
    `export const ICONS = Object.freeze({\n${config.entries.map(([alias, official]) => `  ${JSON.stringify(alias)}: ${component(official)},`).join("\n")}\n});\n`;
}

function provenance(config, assets, generated) {
  const files = Object.fromEntries([...assets].map(([file, bytes]) => [file, {
    archiveEntry: file === "LICENSE" ? "package/LICENSE" : "package/icons/" + file,
    sha256: sha256(bytes),
  }]));
  return json({
    schemaVersion: 1,
    source: config.source,
    configSha256: config.configSha256,
    files,
    generated: { file: "internal/ui/frontend/components/icon-map.ts", sha256: sha256(generated) },
  });
}

function check(config) {
  const expectedNames = ["LICENSE", "SOURCES.json", ...config.names.map(name => name + ".svg")].sort();
  const actualNames = readdirSync(ASSETS).sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) {
    throw new Error("Official SVG asset set differs from icons.json; import the pinned package again");
  }
  const assets = new Map(["LICENSE", ...config.names.map(name => name + ".svg")].map(file => [file, readFileSync(resolve(ASSETS, file))]));
  const generated = generatedScript(config, assets);
  if (readFileSync(resolve(ASSETS, "SOURCES.json"), "utf8") !== provenance(config, assets, generated)) {
    throw new Error("Source hashes or provenance differ; review the assets and import the pinned package again");
  }
  if (readFileSync(GENERATED, "utf8") !== generated) {
    throw new Error("icon-map.ts differs from the official SVGs; import the pinned package again");
  }
  console.log(`Icons OK: ${config.entries.length} legacy names, ${config.names.length} official SVGs, LICENSE, source hashes and generated constants (${config.source.package}@${config.source.version}).`);
}

function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || args[0]?.startsWith("-") && args[0] !== "--check") {
    throw new Error("Usage: node scripts/sync-ui-icons.mjs [archive.tgz | --check]");
  }
  const config = configuration();
  if (args[0] === "--check") return check(config);
  const archive = args[0]
    ? resolve(args[0])
    : resolve(ROOT, `.visual-design/ux-system/vendor/lucide-static-${config.source.version}.tgz`);
  const assets = importAssets(config, archive);
  const generated = generatedScript(config, assets);
  mkdirSync(ASSETS, { recursive: true });
  for (const [file, bytes] of assets) writeFileSync(resolve(ASSETS, file), bytes);
  writeFileSync(GENERATED, generated);
  writeFileSync(resolve(ASSETS, "SOURCES.json"), provenance(config, assets, generated));
  check(config);
}

try { main(); }
catch (error) { console.error("sync-ui-icons: " + error.message); process.exitCode = 1; }
